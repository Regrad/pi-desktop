const { app, BrowserWindow, ipcMain } = require("electron");
const assert = require("node:assert/strict");
const path = require("node:path");
const os = require("node:os");
const { mkdtempSync } = require("node:fs");
const { rm } = require("node:fs/promises");
const appRoot = process.env.PI_SMOKE_APP_ROOT || path.resolve(__dirname, "..");
const temporary = mkdtempSync(path.join(os.tmpdir(), "pi-history-menu-smoke-"));
app.setPath("userData", temporary);
app.whenReady().then(async () => {
  let window;
  let exitCode = 0;
  try {
    const conversation = { id: "smoke", title: "Selection smoke", status: "idle", createdAt: new Date(1).toISOString(), updatedAt: new Date(2).toISOString() };
    const state = { isStreaming: false, isCompacting: false, thinkingLevel: "medium", steeringMessages: [], followUpMessages: [] };
    const sent = [], queued = [];
    ipcMain.handle("desktop:bootstrap", () => ({ interfaceLanguage: "ru", projects: [], conversations: [conversation], archivedConversations: [], activeConversationId: "smoke", dataDir: temporary, sessionsDir: temporary }));
    ipcMain.handle("desktop:open-conversation", () => ({ conversation, messages: [{ role: "assistant", content: [{ type: "text", text: "Проверяем выделенный текст из истории." }], stopReason: "stop", timestamp: 2 }], state, models: [], thinkingLevels: ["medium"], commands: [], entries: [], compactions: [], queuedPrompts: [], extensionState: { extensionPaths: [], activeTools: [], tools: [], commandDiagnostics: [], shortcutDiagnostics: [], errors: [] }, extensionUi: { statuses: {}, widgets: [], headerLines: [], footerLines: [], workingVisible: true, pendingDialogs: [] } }));
    ipcMain.handle("pi:set-editor-text", () => undefined);
    ipcMain.handle("pi:send-prompt", (_event, id, message, attachments) => { sent.push({ id, message, attachments }); });
    ipcMain.handle("desktop:queue-prompt", (_event, id, message, attachments) => { queued.push({ id, message, attachments }); return []; });
    window = new BrowserWindow({ show: false, width: 1100, height: 800, webPreferences: { preload: path.join(appRoot, "dist-electron/electron/preload.cjs"), contextIsolation: true, nodeIntegration: false, sandbox: false } });
    window.webContents.on("console-message", event => {
      if (event.level === "error") console.error("Renderer:", event.message);
    });
    await window.loadFile(path.join(appRoot, "dist/index.html"));
    const js = code => window.webContents.executeJavaScript(code);
    const wait = condition => js(`new Promise((resolve,reject)=>{const end=Date.now()+5000;function check(){if(${condition})return resolve();if(Date.now()>end)return reject(Error(${JSON.stringify(condition)}));setTimeout(check,20);}check();})`);
    await wait("document.querySelector('article.message.assistant') && document.querySelector('.composer textarea')");
    const draft = text => js(`(() => { const e=document.querySelector('.composer textarea'); Object.getOwnPropertyDescriptor(HTMLTextAreaElement.prototype,'value').set.call(e,${JSON.stringify(text)});e.dispatchEvent(new Event('input',{bubbles:true})); })()`);
    const open = () => js(`(() => {const e=document.querySelector('article.message.assistant p'); const range=document.createRange();range.selectNodeContents(e);const s=window.getSelection();s.removeAllRanges();s.addRange(range);e.dispatchEvent(new MouseEvent('contextmenu',{bubbles:true,cancelable:true,clientX:1098,clientY:798}));})()`);
    const action = label => js(`Array.from(document.querySelectorAll('.history-context-menu button')).find(e=>e.textContent===${JSON.stringify(label)}).click()`);
    await draft("Мой несохранённый черновик");
    await open();
    await wait("document.querySelector('.history-context-menu')");
    assert.deepEqual(await js("Array.from(document.querySelectorAll('.history-context-menu button')).map(e=>e.textContent)"), ["Копировать", "Добавить в чат", "Подробнее"]);
    assert.equal(await js("(()=>{const r=document.querySelector('.history-context-menu').getBoundingClientRect();return r.right<=innerWidth&&r.bottom<=innerHeight})()"), true);
    await js("Object.defineProperty(navigator,'clipboard',{configurable:true,value:{writeText:async text=>{window.copiedSelection=text;}}})");
    await action("Копировать");
    await wait("!document.querySelector('.history-context-menu')");
    assert.equal(await js("window.copiedSelection"), "Проверяем выделенный текст из истории.");
    await open(); await wait("document.querySelector('.history-context-menu')");
    await action("Добавить в чат"); await wait("document.querySelector('.history-quote')");
    assert.equal(sent.length, 0);
    assert.equal(await js("document.querySelector('.composer textarea').value"), "Мой несохранённый черновик");
    await js("document.querySelector('.history-quote button').click()"); await wait("!document.querySelector('.history-quote')");
    await open(); await wait("document.querySelector('.history-context-menu')");
    await action("Добавить в чат"); await wait("document.querySelector('.history-quote')");
    await js("document.querySelector('.composer .send-button').click()");
    await wait("document.querySelector('.composer textarea').value==='' && !document.querySelector('.history-quote')");
    assert.equal(sent.length, 1);
    assert.match(sent[0].message, /> Проверяем выделенный текст из истории\./);
    assert.match(sent[0].message, /Сообщение пользователя:\nМой несохранённый черновик$/);
    await draft("Не отправлять этот черновик");
    await open(); await wait("document.querySelector('.history-context-menu')");
    await action("Добавить в чат"); await wait("document.querySelector('.history-quote')");
    await open(); await wait("document.querySelector('.history-context-menu')");
    await action("Подробнее"); await wait("!document.querySelector('.history-context-menu')");
    assert.equal(sent.length, 2);
    assert.match(sent[1].message, /Объясни подробнее выделенный фрагмент\./);
    assert.ok(!sent[1].message.includes("Не отправлять этот черновик"));
    assert.equal(await js("document.querySelector('.composer textarea').value"), "Не отправлять этот черновик");
    assert.equal(await js("document.querySelectorAll('.history-quote').length"), 1);
    window.webContents.send("pi:event", { conversationId: "smoke", event: { type: "agent_start" } });
    await wait("document.querySelector('.send-button.stop')");
    await open(); await wait("document.querySelector('.history-context-menu')");
    await action("Подробнее"); await wait("!document.querySelector('.history-context-menu')");
    assert.equal(queued.length, 1);
    assert.match(queued[0].message, /Объясни подробнее выделенный фрагмент\./);
    assert.equal(await js("document.querySelector('.composer textarea').value"), "Не отправлять этот черновик");
    console.log("HISTORY MENU OK: copy, quote add/remove/send, draft preservation, explain and working queue");
  } catch (error) { console.error(error); exitCode = 1; }
  finally { window?.destroy(); await rm(temporary, { recursive: true, force: true }); app.exit(exitCode); }
});
